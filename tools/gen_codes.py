"""Generate premium unlock codes.

    python tools/gen_codes.py 50

Appends plaintext codes to private/codes.csv (never deployed, gitignored)
and rewrites js/codes.js with the SHA-256 hashes of ALL codes so far.
Sell a code -> mark it used in the CSV.
"""
import csv, hashlib, secrets, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "private" / "codes.csv"
JS = ROOT / "js" / "codes.js"
ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"  # no 0/O/1/I confusion


def new_code():
    part = lambda: "".join(secrets.choice(ALPHABET) for _ in range(4))
    return f"CNV-{part()}-{part()}"


def code_hash(code):
    return hashlib.sha256(("convite:" + code.strip().upper()).encode()).hexdigest()


def main(n):
    CSV.parent.mkdir(exist_ok=True)
    rows = list(csv.reader(CSV.open(encoding="utf-8"))) if CSV.exists() else [["code", "vendido_a"]]
    rows += [[new_code(), ""] for _ in range(n)]
    with CSV.open("w", newline="", encoding="utf-8") as f:
        csv.writer(f).writerows(rows)
    hashes = ",\n  ".join(f"'{code_hash(r[0])}'" for r in rows[1:])
    JS.write_text(f"// Generated by tools/gen_codes.py. Do not edit.\nexport const HASHES = new Set([\n  {hashes}\n]);\n", encoding="utf-8")
    print(f"{n} códigos nuevos, {len(rows) - 1} en total -> {CSV}")


if __name__ == "__main__":
    # self-check: hash must match js/premium.js (prefix 'convite:' + uppercase)
    assert code_hash(" cnv-abcd-efgh ") == hashlib.sha256(b"convite:CNV-ABCD-EFGH").hexdigest()
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 50)
